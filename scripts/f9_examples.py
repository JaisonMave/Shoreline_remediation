"""Write the F9 example reports (docs/F9_PIPELINE_PLAN.md) to results/f9_pipeline/: JSON per case plus summary.txt.

    python -m scripts.f9_examples
"""
from __future__ import annotations

import sys
import warnings
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
warnings.filterwarnings("ignore")

from src.shoreline_remediation import decision_pipeline as dp  # noqa: E402
from src.shoreline_remediation import site_evidence as se  # noqa: E402
from src.shoreline_remediation.data_model import Scenario  # noqa: E402

OUT = ROOT / "results" / "f9_pipeline"


def cases() -> dict:
    sites = se.load_sites()
    cell = sites[sites.cell == "8018_32612"].iloc[0].to_dict()
    return {
        "marsh_8018_32612": ("Heavy salt-marsh edge cell 8018_32612 (Bay Jimmy, Barataria)", lambda: dp.run_decision(cell)),
        "rocky_shore": ("Rocky shore (bedrock), heavy oil, 80% coverage",
                        lambda: dp.run_decision(Scenario(shoreline_type="bedrock", oil_category="heavy", oil_coverage=80.0,
                                                         penetration_depth_cm=2.0, wave_exposure="high"))),
        "sand_beach": ("Sand beach, medium oil, 60% coverage",
                       lambda: dp.run_decision(Scenario(shoreline_type="sand_beach", oil_category="medium", oil_coverage=60.0))),
        "mangrove": ("Mangrove fringe, medium oil, 60% coverage",
                     lambda: dp.run_decision(Scenario(shoreline_type="mangrove", oil_category="medium", oil_coverage=60.0),
                                             habitat="mangrove")),
    }


def summarise(title: str, report: dp.DecisionReport) -> list[str]:
    lines = [f"== {title}", f"scope tier: {report.scope_tier}", f"headline: {report.headline}",
             "classes: " + "; ".join(f"{c}: {', '.join(v) or '-'}" for c, v in report.classes().items())]
    for r in report.options:
        if r["recommendation_class"] == "E":
            why = r["exclusion_reasons"][0]["detail"] if r["exclusion_reasons"] else ""
            lines.append(f"  excluded {r['option']}: {why[:150]}")
    for r in report.natural_recovery["reference"]:
        if r.get("value") is not None:
            lines.append(f"  reference: {r['quantity']} = {r['value']:.2f} (90% {r['lo90']:.2f} to {r['hi90']:.2f}) "
                         f"{r['unit']} [{r['model_id']}, {r['state']}]")
        else:
            lines.append(f"  reference: {r['quantity']}: {r.get('status', 'no model')}")
    lines.append(f"  models used: {', '.join(report.version['models_used']) or 'none'}")
    return lines + [""]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    lines = ["F9 pipeline example reports (generated by scripts/f9_examples.py; numbers are read from the JSON reports)", ""]
    for key, (title, run) in cases().items():
        report = run()
        (OUT / f"{key}.json").write_text(report.to_json(), encoding="utf-8")
        lines += summarise(title, report)
    (OUT / "summary.txt").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
